// Generates src/api/schemas.gen.ts (zod schemas + types) from the backend's
// OpenAPI document, src/api/openapi.json. Run `npm run gen:api` after copying
// a new openapi.json from the API repo; never edit the output by hand.
//
// Mapping (OpenAPI 3.1 → zod 4):
//   enum                     → z.enum([...])            closed: an unknown value fails loudly
//   anyOf [X, {type: null}]  → X.nullable()
//   not in `required`        → .optional()
//   integer / minimum / max  → z.number().int().min().max()
//   format: date-time        → z.iso.datetime({ offset: true })
//   format: uuid             → z.string()               ids are opaque here; the server owns their format
//   additionalProperties     → z.record(z.string(), …)  when there are no named properties
//   objects                  → z.object (unknown extra fields are dropped, so additive API changes do not break the app)
import { readFileSync, writeFileSync } from 'node:fs';

const SRC = 'src/api/openapi.json';
const OUT = 'src/api/schemas.gen.ts';
const doc = JSON.parse(readFileSync(SRC, 'utf8'));
const schemas = doc.components.schemas;

const refName = (ref) => ref.replace('#/components/schemas/', '');
const isNull = (s) => s && s.type === 'null';

function deps(s, out = new Set()) {
  if (!s || typeof s !== 'object') return out;
  if (Array.isArray(s)) { for (const x of s) deps(x, out); return out; }
  if (s.$ref) out.add(refName(s.$ref));
  for (const v of Object.values(s)) deps(v, out);
  return out;
}

function zod(s) {
  if (s.$ref) return refName(s.$ref);
  if (s.anyOf || s.oneOf) {
    const parts = s.anyOf ?? s.oneOf;
    const nonNull = parts.filter((p) => !isNull(p));
    const inner = nonNull.length === 1 ? zod(nonNull[0]) : `z.union([${nonNull.map(zod).join(', ')}])`;
    return nonNull.length < parts.length ? `${inner}.nullable()` : inner;
  }
  if (s.enum) return `z.enum([${s.enum.map((v) => JSON.stringify(v)).join(', ')}])`;
  if (s.const !== undefined) return `z.literal(${JSON.stringify(s.const)})`;
  switch (s.type) {
    case 'string': {
      if (s.format === 'date-time') return 'z.iso.datetime({ offset: true })';
      let z = 'z.string()';
      if (s.minLength != null) z += `.min(${s.minLength})`;
      if (s.maxLength != null) z += `.max(${s.maxLength})`;
      return z;
    }
    case 'integer':
    case 'number': {
      let z = s.type === 'integer' ? 'z.number().int()' : 'z.number()';
      if (s.minimum != null) z += `.min(${s.minimum})`;
      if (s.maximum != null) z += `.max(${s.maximum})`;
      return z;
    }
    case 'boolean': return 'z.boolean()';
    case 'null': return 'z.null()';
    case 'array': return `z.array(${s.items ? zod(s.items) : 'z.unknown()'})`;
    case 'object':
    case undefined: {
      const props = s.properties ?? {};
      const names = Object.keys(props);
      if (!names.length) {
        const ap = s.additionalProperties;
        return `z.record(z.string(), ${ap && typeof ap === 'object' && Object.keys(ap).length ? zod(ap) : 'z.unknown()'})`;
      }
      const required = new Set(s.required ?? []);
      const fields = names.map((n) => {
        const key = /^[A-Za-z_$][\w$]*$/.test(n) ? n : JSON.stringify(n);
        return `  ${key}: ${zod(props[n])}${required.has(n) ? '' : '.optional()'},`;
      });
      return `z.object({\n${fields.join('\n')}\n})`;
    }
    default:
      throw new Error(`Unsupported schema type ${s.type}`);
  }
}

// Dependencies first, so every schema is declared before it is used.
const order = [];
const seen = new Set();
function visit(name, stack = []) {
  if (seen.has(name)) return;
  if (stack.includes(name)) throw new Error(`Circular schema reference: ${[...stack, name].join(' → ')}`);
  for (const d of deps(schemas[name])) if (d !== name) visit(d, [...stack, name]);
  seen.add(name);
  order.push(name);
}
for (const name of Object.keys(schemas).sort()) visit(name);

const lines = [
  '// Generated by scripts/gen-api-schemas.mjs from src/api/openapi.json',
  `// (${doc.info.title} ${doc.info.version}). Do not edit by hand: run \`npm run gen:api\`.`,
  "import { z } from 'zod';",
  '',
];
for (const name of order) {
  const s = schemas[name];
  if (s.description) lines.push(`/** ${s.description.replace(/\*\//g, '*\\/').replace(/\s*\n\s*/g, ' ')} */`);
  lines.push(`export const ${name} = ${zod(s)};`);
  lines.push(`export type ${name} = z.infer<typeof ${name}>;`);
  lines.push('');
}
lines.push('/** Every schema type by name, as `components["schemas"]` was in the OpenAPI types. */');
lines.push('export interface Schemas {');
for (const name of order) lines.push(`  ${name}: ${name};`);
lines.push('}');
lines.push('');
writeFileSync(OUT, lines.join('\n'));
console.log(`Wrote ${OUT}: ${order.length} schemas.`);
